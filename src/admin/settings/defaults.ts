const isObject = (v: unknown): v is Section => typeof v === "object" && v !== null && !Array.isArray(v);

/** Mezcla profunda: los valores guardados sobrescriben los predeterminados. */
export const mergeDeep = (base: Section, over?: Section): Section => {
  const out: Section = { ...base };
  if (!over) return out;
  for (const key of Object.keys(over)) {
    out[key] = isObject(base[key]) && isObject(over[key]) ? mergeDeep(base[key], over[key]) : over[key];
  }
  return out;
};
